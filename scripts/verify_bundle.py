#!/usr/bin/env python3
"""Verify MK231 full cumulative bundle content (Python standard library only).

Usage:
    python scripts/verify_bundle.py --root .
    python path/to/scripts/verify_bundle.py --root path/to/extracted/staging

Manifest is generated by the package author; do not regenerate the manifest to
suppress verification failures before establishing why files differ.
"""
import argparse
import hashlib
import json
from pathlib import Path
from zipfile import ZipFile, BadZipFile
import sys


def sha256_file(path):
    h = hashlib.sha256()
    with path.open('rb') as f:
        for b in iter(lambda: f.read(1024 * 1024), b''):
            h.update(b)
    return h.hexdigest()


def check(root: Path) -> int:
    manifest_path = root / 'bundle_manifest.json'
    if not manifest_path.is_file():
        print('ERROR: bundle_manifest.json missing')
        return 1
    data = json.loads(manifest_path.read_text(encoding='utf-8'))
    assert data['bundle_id'] == 'MK231_FULL_CUMULATIVE_LIVE_MODEL_v1.0.0'
    errors = []
    known = {e['path'] for e in data['files']}
    for e in data['files']:
        rel = Path(e['path'])
        if rel.is_absolute() or '..' in rel.parts:
            errors.append(f'Unsafe path in manifest: {rel}')
            continue
        f = root / rel
        if not f.is_file():
            errors.append(f'Missing: {rel}')
            continue
        if f.stat().st_size != e['bytes']:
            errors.append(f'Size differs: {rel}')
        if sha256_file(f) != e['sha256']:
            errors.append(f'SHA256 mismatch: {rel}')
    for p in root.rglob('*'):
        if not p.is_file():
            continue
        rel = p.relative_to(root)
        if '.git' in rel.parts or '_inbox' in rel.parts:
            errors.append(f'Forbidden path included: {rel}')
        # Staging can contain its own ignored files only outside the scanned root.
        if str(rel).replace('\\', '/') not in known and str(rel) not in {'bundle_manifest.json', 'SHA256SUMS.txt'}:
            errors.append(f'Unexpected file, not in manifest: {rel}')
    archived = root / 'provenance' / 'MK_Fantasy_Live_Model_v0.3.0_ORIGINAL.zip'
    if archived.is_file():
        try:
            with ZipFile(archived) as zipf:
                corrupt = zipf.testzip()
                if corrupt:
                    errors.append(f'Old ZIP corrupt: {corrupt}')
                else:
                    orig = [n for n in zipf.namelist() if not n.endswith('/')]
                    if len(orig) != 33:
                        errors.append(f'Original checkpoint expected 33 files, got {len(orig)}')
                    for member in orig:
                        prefix = 'MK_Fantasy_Live_Model_v0.3.0/'
                        if not member.startswith(prefix):
                            errors.append(f'Unexpected old ZIP entry prefix: {member}')
                            continue
                        rel = Path('history/v0.3.0') / member[len(prefix):]
                        extract = root / rel
                        if not extract.is_file() or hashlib.sha256(zipf.read(member)).hexdigest() != sha256_file(extract):
                            errors.append(f'Old archive extracted bytes differ: {rel}')
        except BadZipFile:
            errors.append('Original ZIP invalid')
    else:
        errors.append('Original full v0.3.0 ZIP unavailable')
    mandated = [
        'Executable.md', 'AGENTS.md', '.gitignore', 'README.md', 'CURRENT_LIVE_MODEL.md',
        'constitution/WORKSHOP_AND_WRITING.md', 'constitution/CHROMATIC_PRESENTATION.md',
        'canon/02_EIGHT_PROPHECIES_OF_MAGIC.md',
        'story/01_KIRA_AND_AFFLICTION.md', 'story/02_THE_BLACK_PROPHECY.md',
        'visuals/current/BLUE_SIX_FEMALE_LEVIATHANS_2026-10-09.png',
        'history/v0.3.0/visuals/the_horizon_leviathan_nine_cosmic_forms.png',
    ]
    for name in mandated:
        if not (root / name).is_file():
            errors.append(f'Critical file absent: {name}')
    if errors:
        print(f'FAIL: {len(errors)} problem(s) in {len(data["files"])} manifest files')
        for err in errors[:90]:
            print('  -', err)
        if len(errors) > 90:
            print('  ...', len(errors) - 90, 'more')
        return 1
    mb = sum(e['bytes'] for e in data['files']) / (1024 * 1024)
    print(f'PASS: {len(data["files"])} files ({mb:.2f} MiB uncompressed); old 33-file ZIP intact and identical; no _inbox in package.')
    return 0

if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--root', type=Path, default=Path.cwd())
    args = p.parse_args()
    sys.exit(check(args.root.resolve()))
